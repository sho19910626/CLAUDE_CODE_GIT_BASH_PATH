/** ヒアリング内容をプロンプトに載せる */
function buildBriefBlock(b: AvatarBrief): string {
  const rows: [string, string][] = [
    ["目的", GOAL_LABELS[b.goal]],
    ["主戦場", PLATFORM_LABELS[b.platform]],
    ["顔出し方針", FACE_LEVEL_LABELS[b.faceLevel]],
    ["企業名・屋号", b.companyName],
    ["事業内容", b.business],
    ["発信者のプロフィール", b.speaker],
    ["★ 本人が普段お客様に話していること・語り口", b.speakerVoice],
    ["希望するアバターの見た目・声", b.lookRequest],
    ["商材・価格・提供形態", b.product],
    ["★ 届けたい相手", b.target],
    ["★ よく聞かれる質問・つまずくところ", b.faq],
    ["実績・数字・事例", b.proof],
    ["参考アカウント・競合", b.competitors],
    ["これまでの発信状況と続かなかった理由", b.history],
    ["言ってはいけないこと・NG表現", b.ngList],
    ["使える素材", b.assets],
    ["投稿本数・運用体制・使用ツール", b.operation],
    ["予算・料金の想定", b.budget],
    ["その他メモ", b.memo],
  ];
  const filled = rows
    .filter(([, v]) => v && v.trim())
    .map(([k, v]) => `- ${k}: ${v.trim()}`);
  const empty = rows.filter(([, v]) => !v || !v.trim()).map(([k]) => k);

  return [
    "## ヒアリング内容",
    ...filled,
    empty.length > 0
      ? `\n未入力の項目: ${empty.join(" / ")}\n(未入力の項目は、事業内容から妥当な範囲で補ってください。ただし数字・実績・価格は補わず、素材が必要な箇所は「顧客に確認する」形で書いてください)`
      : "",
  ]
    .filter(Boolean)
    .join("\n");
}

/** 全段階に共通する前提ブロック */
function buildContextBlock(args: {
  brief: AvatarBrief;
  siteBlock: string;
  hasImages: boolean;
}): string {
  const { brief, siteBlock, hasImages } = args;
  return [
    GOAL_BRIEF[brief.goal],
    "",
    PLATFORM_BRIEF[brief.platform],
    "",
    FACE_BRIEF[brief.faceLevel],
    "",
    buildBriefBlock(brief),
    "",
    siteBlock,
    "",
    hasImages
      ? "## 添付写真について\n添付されているのは、発信者本人・商品・現場の実際の写真です。写真から人物の雰囲気・商材の質感・撮れる素材の範囲を読み取り、アバターの設計とBロールの指示に反映してください。写真から読み取れる事実は根拠として使って構いません。"
      : "",
  ]
    .filter(Boolean)
    .join("\n");
}

