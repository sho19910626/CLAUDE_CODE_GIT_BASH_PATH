/** 職種名と求人タイトルからプロファイルを引く */
export function matchJobType(job: JobRecord): JobTypeProfile | null {
  const text = `${job.jobCategory ?? ""} ${job.copy?.title ?? ""} ${job.name ?? ""}`;
  return JOB_TYPE_PROFILES.find((p) => p.match.test(text)) ?? null;
}

