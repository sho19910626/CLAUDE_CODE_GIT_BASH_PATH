// ===== 考察文の組み立て =====

export interface JobTypeInsight {
  /** 見出しに使うラベル(職種名) */
  label: string | null;
  /** 本文 */
  text: string;
  /** 原稿に書かれているべき項目のうち、見当たらないもの */
  missing: string[];
}

/**
 * 項目名から、原稿と照合するためのキーワードを取り出す。
 *
 * 「体験入店の可否」をそのまま探すと、原稿に「体験入店OK」と書いてあっても
 * 見つからず「未記載」と誤判定してしまう。「〜の可否」「〜の有無」といった
 * 言い回しを落として、実体のある語だけで照合する。
 */
function keywords(item: string): string[] {
  return item
    .split(/と条件|可否|の(?:有無|別|実態|扱い|範囲|量|率|回数)|[\s/・、()（）]|など/)
    .map((w) => w.replace(/[のをはがかと可]+$/, "").trim())
    .filter((w) => w.length >= 2);
}

/** 原稿にその項目に触れた記述があるか、ざっくり見る */
function mentions(text: string, item: string): boolean {
  const words = keywords(item);
  return words.length === 0 || words.some((w) => text.includes(w));
}

/**
 * 職種・雇用形態ならではの考察を組み立てる。
 * 詰まっている段階(stage)に対応する見立てを優先して出す。
 */
export function buildJobTypeInsight(
  job: JobRecord,
  stage: FunnelStage | null
): JobTypeInsight | null {
  const profile = matchJobType(job);
  const employment = EMPLOYMENT_PROFILES[job.employmentType];
  if (!profile && !employment) return null;

  const parts: string[] = [];

  if (profile) {
    parts.push(`【${profile.label}】${profile.audience}。`);
    const stageNote = stage ? profile.byStage[stage] : undefined;
    if (stageNote) parts.push(`${stageNote}。`.replace(/。。$/, "。"));
  }

  if (employment) {
    parts.push(employment.flow + "。");
    const empNote = stage ? employment.byStage[stage] : undefined;
    if (empNote) parts.push(`${empNote}。`.replace(/。。$/, "。"));
  }

  if (profile?.caution) {
    parts.push(`なお、${profile.caution}。`.replace(/。。$/, "。"));
  }

  // 原稿が登録されていれば、この職種で必須の項目が書かれているか照合する
  const copy = `${job.copy?.title ?? ""} ${job.copy?.catch ?? ""} ${job.copy?.description ?? ""}`;
  const missing =
    profile && copy.trim().length > 0
      ? profile.decisive.filter((d) => !mentions(copy, d))
      : [];

  if (missing.length > 0) {
    const shown = missing.slice(0, 4);
    parts.push(
      `この職種で応募判断を分けるのは「${profile!.decisive.join("」「")}」です。` +
        `いまの原稿には「${shown.join("」「")}」` +
        (missing.length > shown.length ? `ほか${missing.length - shown.length}件` : "") +
        `の記載が見当たらないので、ここを書き足すのが最短です。`
    );
  } else if (profile && copy.trim().length === 0) {
    parts.push(
      `この職種で応募判断を分けるのは「${profile.decisive.join("」「")}」です。原稿を貼り付けると、書けているかどうかを照合します。`
    );
  }

  return {
    label: profile?.label ?? null,
    text: parts.join(" "),
    missing,
  };
}

// ===== 職種名の言い換え =====

/**
 * 求人名から市区町村を取り出す。
 *
 * 「【小牧市】フォークリフト」「小牧市/リフト」のような書き方を拾う。
 * 見つからなければ null(都道府県で代用する)。
 */
export function extractCity(text: string): string | null {
  const m = text.match(/([一-龥ぁ-んァ-ヶー]{1,8}?[市区町村])/);
  return m ? m[1] : null;
}

export interface TitleSuggestion {
  /** そのまま職種名欄に入れられる案 */
  title: string;
  /** なぜ競合が減るのか */
  reason: string;
}

/**
 * 職種名の言い換え案を、この求人の実データから組み立てる。
 *
 * Indeed の職種名は検索語との突き合わせに使われるので、
 * 一般語だけだと同エリアの同職種すべてと同じ枠で競り、クリック単価が上がる。
 * 地名・機種・条件を足すと検索母数は減るが競合も減り、単価が下がる。
 *
 * ⚠ ここで出すのは「型」であって事実ではない。
 *    実態に当てはまらない言葉を使うと、集めても応募にならないので、
 *    文言にもその注意を必ず添える。
 */
export function suggestJobTitles(job: JobRecord): TitleSuggestion[] {
  const profile = matchJobType(job);
  const base = (job.jobCategory || job.name).trim();
  const place = extractCity(job.name) ?? extractCity(job.jobCategory ?? "") ?? job.prefecture;
  const out: TitleSuggestion[] = [];

  // すでに職種名に地名が入っているなら、足しても意味がない
  if (place && !base.includes(place)) {
    out.push({
      title: `${place} ${base}`,
      reason: "地名を入れると、通える範囲の人にだけ出るようになります。無関係なエリアへのクリックに払わずに済みます",
    });
  }

  const angles = profile?.titleAngles;
  if (angles) {
    if (angles.specifics.length > 0) {
      const picks = angles.specifics.slice(0, 3);
      // 「一般事務 + 事務」のような重なりを避ける。
      // 具体語のほうが職種名を含んでいるなら、足すのではなく置き換える
      const overlaps = picks.some((x) => x.includes(base) || base.includes(x));
      out.push({
        title: overlaps
          ? `${picks.join(" / ")} のうち実際のものに置き換える`
          : `${base}（${picks.join(" / ")} のうち実際のもの）`,
        reason: `仕事そのものを具体化する言い方です。「${base}」だけで探している人より、${picks[0]}で探している人のほうが競合が薄く、応募までの距離も近くなります`,
      });
    }
    if (angles.conditions.length > 0) {
      out.push({
        title: `${base}（${angles.conditions.slice(0, 3).join(" / ")} のうち当てはまるもの）`,
        reason: "条件で探している人に直接当てにいく形です。条件が合う人だけが来るので、クリック単価も応募率も同時に良くなります",
      });
    }
  }

  // 給与が登録されていれば、数字を前に出す形も出す
  if (job.wage?.min !== undefined) {
    const unit = job.wage.type === "hourly" ? "時給" : job.wage.type === "daily" ? "日給" : "月給";
    out.push({
      title: `${base}｜${unit}${job.wage.min.toLocaleString("ja-JP")}円`,
      reason: "金額で絞り込んで探す層に当てにいく形です。相場より高いときだけ有効で、低いときは逆効果になります",
    });
  }

  return out.slice(0, 4);
}
