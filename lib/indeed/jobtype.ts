// 職種・雇用形態ならではの考察。
//
// 「クリック率が低い」までは数字で分かるが、その先の「なぜ低いのか」は職種で違う。
// フォークリフトなら有資格者という限られた母集団の取り合いだから給与が効くし、
// ナイトのキャストなら高時給が前提なので給与では差がつかない。
// 介護は売り手市場でクリックは来るが、夜勤と人員配置が書いていないと応募されない。
//
// ここは統計ではなく、求人媒体の運用でくり返し観測される「型」を言語化したもの。
// 数値診断(diagnose.ts)がどの段階が詰まっているかを決め、
// この層がその段階について「この職種ならこういうことが起きている」を足す。

import type { EmploymentTypeId, FunnelStage, JobRecord } from "./types";

export interface JobTypeProfile {
  id: string;
  label: string;
  /** 職種名・求人タイトルから判定する */
  match: RegExp;
  /** どんな人が応募してくる市場か */
  audience: string;
  /** 段階ごとの、この職種ならではの見立て */
  byStage: Partial<Record<FunnelStage, string>>;
  /** 応募判断を分ける項目。原稿に無ければ書き足す対象になる */
  decisive: string[];
  /**
   * 職種名を具体化するときに使える語。
   *
   * Indeed の職種名は検索語との突き合わせに使われる。
   * 「フォークリフト」のような一般語だけだと同エリアの同職種すべてと
   * 同じ枠で競るのでクリック単価が上がる。機種・工程・勤務形態を足すと
   * 検索される回数は減るが競合も減り、単価が下がる。
   *
   *   specifics  … 仕事そのものを具体化する言い方(機種・工程・区分)
   *   conditions … 条件で絞る言い方(勤務形態・待遇)
   *
   * ⚠ 実態に当てはまるものだけを使う。違う言葉で集めても応募にならない。
   */
  titleAngles?: { specifics: string[]; conditions: string[] };
  /** 法令・表記でこの職種特有の注意 */
  caution?: string;
}

