export interface JobTypeProfile {
  id: string;
  label: string;
  /** 職種名・求人タイトルから判定する */
  match: RegExp;
  /** どんな人が応募してくる市場か */
  audience: string;
  /** 段階ごとの、この職種ならではの見立て */
  byStage: Partial<Record<FunnelStage, string>>;
  /** 応募判断を分ける項目。原稿に無ければ書き足す対象になる */
  decisive: string[];
  /**
   * 職種名を具体化するときに使える語。
   *
   * Indeed の職種名は検索語との突き合わせに使われる。
   * 「フォークリフト」のような一般語だけだと同エリアの同職種すべてと
   * 同じ枠で競るのでクリック単価が上がる。仕事の中身を具体化すると
   * 検索される回数は減るが競合も減り、単価が下がる。
   *
   *   contexts   … 「●●の△△」の ●● に入る語(業界・現場・扱うもの)
   *   specifics  … 仕事そのものを具体化する言い方(機種・工程・区分)
   *
   * ⚠ 勤務地・給与・雇用形態・待遇はここに入れない。
   *   Indeed の掲載基準で職種名には職種名以外を入れないことになっており、
   *   入れると「質が低い」と判定されて検索露出が落ちる。
   *   それらは勤務地欄・給与欄・仕事内容欄に入れる。
   *
   * ⚠ 実態に当てはまるものだけを使う。違う言葉で集めても応募にならない。
   */
  titleAngles?: { contexts: string[]; specifics: string[] };
  /** 法令・表記でこの職種特有の注意 */
  caution?: string;
}

