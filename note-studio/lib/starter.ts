// 実績がまだ無い人の売り方。
//
// このツールは「実績を数字で書く」ことを軸にしている。
// では実績が無い人は稼げないのか、というとそうではない。
// ただし**同じ書き方では売れない**。実績を語る代わりに何を売るかを変える。
//
// ⚠ ここで絶対にやらないこと:
//   - 実績があるかのように書かせる(嘘の数字・肩書き)
//   - 「専門家」「プロ」を名乗らせる
//   実績ゼロで専門家を装うと、読者は必ず気づく。返金と信用の失墜になり、
//   一度落ちた信用では二度と売れない。だから最初から名乗らせない。
//
// 代わりに使うのが、下の4つの型。どれも「実績が無いこと」を
// 隠さずに成立する売り方で、note で実際に売れている形。

export type StarterShape = "process" | "research" | "tool" | "translate";

export interface StarterPlaybook {
  shape: StarterShape;
  label: string;
  /** どういう売り方か */
  summary: string;
  /** 読者が何にお金を払うのか(=価値の源) */
  valueSource: string;
  /** 実際に売るもの */
  sellables: string[];
  /** 最初の1本の型 */
  firstArticle: string;
  /** 現実的な価格帯 */
  priceRange: string;
  /** この型が向く人 */
  fitsWho: string;
  /** この型でやってはいけないこと */
  neverDo: string[];
  /** 実績が貯まるまでの期間の目安 */
  rampUp: string;
}

