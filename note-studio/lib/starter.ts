export function playbookFor(shape: StarterShape): StarterPlaybook {
  return STARTER_PLAYBOOKS.find((p) => p.shape === shape) ?? STARTER_PLAYBOOKS[0];
}

/** 実績ゼロのときに、AI へ渡す指針 */
export function starterGuidance(shapes: StarterShape[]): string {
  const picked = shapes.length > 0 ? shapes.map(playbookFor) : STARTER_PLAYBOOKS;

  return `# ⚠ この人には、まだ語れる実績がありません

実績の数字を使った設計は**できません**。代わりに、下の型で設計してください。

## 絶対に守ること

- **実績があるかのように書かせない。** 数字・肩書き・経験を作らない
- **「専門家」「プロ」を名乗らせない。** 実績ゼロで専門家を装うと読者に見抜かれ、
  一度落ちた信用では二度と売れなくなる
- **「実績が無い」ことを隠さない。** 隠すのではなく、
  「同じ立場だから書けること」に変換する
- 「これだけで稼げる」など、効果を保証する書き方をしない

## 使える型

${picked
  .map(
    (p) => `### ${p.label}
- どういう売り方か: ${p.summary}
- 読者が払う理由: ${p.valueSource}
- 売るもの: ${p.sellables.join(" / ")}
- 最初の1本: ${p.firstArticle}
- 価格帯: ${p.priceRange}
- 向く人: ${p.fitsWho}
- やってはいけない: ${p.neverDo.join(" / ")}
- 売れ始めるまで: ${p.rampUp}`
  )
  .join("\n\n")}

## 設計の順番

1. 上の型から、この人の持ち札で**いま実行できる**ものを選ぶ
2. その型に沿って、最初の1本を決める
3. **最初の90日で「語れる実績」を作ること自体を計画に入れる**
   (記録を取る、調べ切る、道具を作り切る)
4. 実績が出てから、通常の設計に切り替える

計画には、**いつ・何をもって「実績あり」に切り替わるか**を必ず書いてください。`;
}
