// 個人店・単店舗の可能性が高い表記。規模が小さく月10万円の出稿は考えにくいので後回し。
const SINGLE_SHOP_PATTERNS = [
  '美容室', 'ヘアダメージ研究所', 'La fith', 'Reverie', '色染堂',
];

const has = (name, patterns) => patterns.some((p) => name.includes(p));

/**
 * @returns {'派遣・紹介'|'全国大手'|'単店舗'|'地方企業'}
 */
export function classify(name) {
  if (has(name, AGENCY_PATTERNS)) return '派遣・紹介';
  if (has(name, NATIONAL_PATTERNS)) return '全国大手';
  if (has(name, SINGLE_SHOP_PATTERNS)) return '単店舗';
  return '地方企業';
}

// 法人格を持たない＝支店名・店舗名だけで拾えてしまったレコードの検出。
// 親会社を特定してから当たる必要があるため、リストでは要確認フラグを立てる。
export function isCorporate(name) {
  return /株式会社|有限会社|合同会社|合資会社|社会福祉法人|医療法人|学校法人|生活協同組合|㈱|㈲|\(株\)|\(有\)/.test(name);
}

// Indeedの出稿単価が構造的に高い業種。
// 応募が採用に直結しにくく、通年で枠を埋め続ける必要があるため予算が膨らみやすい。
const HIGH_SPEND_INDUSTRIES = new Set(['アミューズメント', '介護', '運送', '飲食', '警備']);

export function industryWeight(industry) {
  return HIGH_SPEND_INDUSTRIES.has(industry) ? 1.2 : 1.0;
}
