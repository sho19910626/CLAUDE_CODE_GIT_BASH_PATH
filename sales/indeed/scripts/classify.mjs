// 個人店・単店舗の可能性が高い表記。規模が小さく月10万円の出稿は考えにくいので後回し。
const SINGLE_SHOP_PATTERNS = [
  '美容室', 'ヘアダメージ研究所', 'La fith', 'Reverie', '色染堂',
];

const has = (name, patterns) => patterns.some((p) => name.includes(p));

/**
 * @param {string} name 企業名
 * @param {string} industry 主要職種カテゴリ（'派遣' なら人材会社と判定する）
 * @returns {'地方企業'|'地方派遣'|'全国大手'|'全国大手派遣'|'単店舗'}
 */
export function classify(name, industry) {
  const staffing = industry === '派遣' || has(name, STAFFING_PATTERNS);
  const national = has(name, NATIONAL_PATTERNS);

  if (staffing) return national ? '全国大手派遣' : '地方派遣';
  if (national) return '全国大手';
  if (has(name, SINGLE_SHOP_PATTERNS)) return '単店舗';
  return '地方企業';
}

